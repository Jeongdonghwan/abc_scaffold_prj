type ModG = 'price' | 'pick' | 'work' | 'rent' | 'base';
const modGroup = (p: Page): ModG => {
  if (/비용|가격|견적|단가/.test(p.mod)) return 'price';
  if (/업체|전문|추천|잘하는곳/.test(p.mod)) return 'pick';
  if (/설치|시공/.test(p.mod) || (!p.mod && p.word === '비계설치')) return 'work';
  if (/임대|렌탈/.test(p.mod) || (!p.mod && p.word === '비계임대')) return 'rent';
  return 'base';
};

