def main():
    wb = load_workbook(SRC, read_only=True)
    rows = list(wb['지역목록'].iter_rows(values_only=True))[1:]
    places, hubs = {}, []
    for rep, unit, parent, alts, life, ndong, dongs in rows:
        f = G[rep]
        hub = None if rep == '서울' else rep
        if hub:
            hubs.append(hub)
        admin = f.get('admin') or f'서울특별시 {f["name"]}'
        places[rep] = dict(key=rep, name=f['name'], kind='시' if unit == '시·군' else '구', hub=hub, parent=parent, admin=admin,
                           traits=f['traits'], homes=f['homes'], roads=f['roads'], spots=f['spots'], site=f['site'],
                           alts=[a.strip() for a in (alts or '').split(',') if a.strip()], subs=[])
        for lv in [x.strip() for x in (life or '').split(',') if x.strip()]:
            nm, tr, st = L[lv]
            places[lv] = dict(key=lv, name=nm, kind='생활권', hub=rep, parent=rep, admin=admin, traits=tr, homes=f['homes'], roads=f['roads'],
                              spots=f['spots'], site=st, alts=[], subs=[])
        for d in re.findall(r'([^,(]+?)(?:\(([^)]*)\))?\s*(?:,|$)', dongs or ''):
            nm, subs = d[0].strip(), [x for x in (d[1] or '').split('·') if x]
            if not nm:
                continue
            places[f'{rep}::{nm}'] = dict(key=nm, name=nm, kind='동', hub=rep, parent=rep, admin=f'{admin} {nm}', traits=f['traits'], homes=f['homes'],
                                          roads=f['roads'], spots=f['spots'], site=f['site'], alts=[], subs=subs)
    # 형제 동 이름(같은 구) — 본문 '함께 다니는 동네'
    for k, p in places.items():
        if p['kind'] == '동':
            p['siblings'] = [q['name'] for q in places.values() if q['kind'] == '동' and q['hub'] == p['hub'] and q['name'] != p['name']]
    out = {'places': places, 'hubs': hubs}
    (ROOT / 'data').mkdir(exist_ok=True)
    json.dump(out, open(ROOT / 'data' / 'places.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    sys.stdout.reconfigure(encoding='utf-8')
    from collections import Counter
    print('places', len(places), Counter(p['kind'] for p in places.values()), 'hubs', len(hubs))


if __name__ == '__main__':
    main()
